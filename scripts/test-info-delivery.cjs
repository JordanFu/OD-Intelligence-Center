const assert = require('node:assert/strict');
const { assessDelivery, daySection, assessReceipt } = require('./check-info-delivery.cjs');

const now = new Date('2026-09-11T04:00:00Z');
const date = '2026-09-11';
const card = `## ${date}\n\n### [F0911-01] 测试事实\n- **信息类型**：新增事实\n- **事件摘要**：已经核实的事实。\n`;
const files = { 'digest.md': card, [`daily/${date}.md`]: card, [`daily-report/${date}.md`]: `# ${date}\n\n当日导读及来源。` };
const info = { latestDate: date, latestCardCount: 1, qualityStatus: 'warn' };
const base = { now, files, info, remoteFiles: files, remoteInfo: info };
assert.equal(assessDelivery(base).status, 'published');
assert.equal(assessDelivery(base).qualityStatus, 'warn');
assert.equal(assessDelivery({ ...base, files: {} }).status, 'overdue');
assert.equal(assessDelivery({ ...base, files: {}, now: new Date('2026-09-11T01:00:00Z') }).status, 'scheduled');
assert.equal(assessDelivery({ ...base, files: {}, now: new Date('2026-09-11T02:00:00Z') }).status, 'running-window');
assert.equal(assessDelivery({ ...base, remoteFiles: {} }).status, 'publish-pending');
assert.equal(assessDelivery({ ...base, remoteFiles: { ...files, 'digest.md': card.replace('核实', '修改') } }).status, 'publish-pending');
assert.equal(assessDelivery({ ...base, remoteInfo: { latestDate: '2026-09-10' } }).status, 'publish-pending');
assert.equal(assessDelivery({ ...base, remoteErrors: ['network'] }).status, 'publication-unverified');
assert.equal(assessDelivery({ ...base, info: { ...info, qualityStatus: 'fail' } }).status, 'quality-blocked');
assert.equal(assessDelivery({ ...base, files: { ...files, [`daily-report/${date}.md`]: '研究状态记录 / 非决策稿' } }).status, 'overdue');
const gaps = Object.fromEntries(Object.entries(files).map(([name, content]) => [name, content.replace('新增事实', '缺口记录')]));
assert.equal(assessDelivery({ ...base, files: gaps, remoteFiles: gaps }).status, 'published-gap');
assert.equal(assessDelivery({ ...base, files: gaps, remoteFiles: gaps }).qualityStatus, 'warn');
assert.equal(daySection(`## 2026-09-12\n新日\n${card}\n## 2026-09-10\n旧日`, date), card.trim());
assert.equal(assessReceipt({ ...assessDelivery(base), checkedAt: '2026-09-10T04:00:00Z' }, now).qualityStatus, 'fail');
assert.equal(assessReceipt(null, now).status, 'check-required');
assert.equal(assessReceipt(null, now).qualityStatus, 'fail');
assert.equal(assessReceipt(assessDelivery(base), now).status, 'published');
assert.equal(assessReceipt({ date, checkedAt: 'bad' }, now).status, 'check-required');
assert.equal(assessReceipt(assessDelivery({ ...base, files: {}, now: new Date('2026-09-11T02:00:00Z') }), now).status, 'overdue');
assert.equal(assessDelivery({ ...base, remoteInfo: { ...info, qualityStatus: 'fail' } }).status, 'publish-pending');
assert.equal(assessDelivery({ ...base, files: { ...files, [`daily/${date}.md`]: card.replace('F0911-01', 'F0911-02') } }).status, 'overdue');
console.log('info delivery: deadline, stale receipt, content parity, gaps, network and quality checks passed');
